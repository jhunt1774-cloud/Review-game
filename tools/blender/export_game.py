"""Export the Blender render for the existing Forest Adventure renderer."""
import argparse
import base64
import json
from pathlib import Path
from collections import deque
from PIL import Image, ImageFilter

parser = argparse.ArgumentParser()
parser.add_argument("render_folder", type=Path)
folder = parser.parse_args().render_folder
repo = Path(__file__).resolve().parents[2]
assets = repo / "assets"
frame = Image.open(folder / "Wildwood.png").convert("RGB")
frame.save(assets / "wildwood-valley.webp", quality=92, method=6)
w,h = 300,200  # ForestWorld's navigation coordinates
mask = Image.open(folder / "Floor.png").convert("L").resize((w,h),Image.Resampling.BOX)
walk = bytearray(int(v>=200) for v in mask.tobytes())
stops = json.loads((folder/"game-stops.json").read_text())
bridge = json.loads((folder/"landmarks.json").read_text())["bridge"]
def index(point):
    x,y=point
    return int(x*w)+int(y*h)*w
for k,point in stops.items():
    if walk[index(point)]:continue
    # The binary threshold can trim a fractional edge cell at a stone footing.
    x,y=point
    nearest=min((i for i,v in enumerate(walk) if v),key=lambda i: ((i%w+.5)-x*w)**2+((i//w+.5)-y*h)**2)
    snapped=[(nearest%w+.5)/w,(nearest//w+.5)/h]
    assert abs(snapped[0]-x)<.009 and abs(snapped[1]-y)<.012,(k,point,snapped)
    stops[k]=snapped
def flood(start, cut):
    seen={start};q=deque(seen)
    while q:
        i=q.popleft();x,y=i%w,i//w
        for a,b in ((x+1,y),(x-1,y),(x,y+1),(x,y-1)):
            nxt=b*w+a
            if 0<=a<w and 0<=b<h and walk[nxt] and nxt not in seen and nxt not in cut:
                seen.add(nxt);q.append(nxt)
    return seen
col,row=int(bridge[0]*w),int(bridge[1]*h)
cut={j*w+col for j in range(row-7,row+8)}
west=flood(index(stops['entry']),cut)
east=flood(index(stops['m3']),cut)
assert not west&east,"An unguarded crossing joins the two banks"
assert all(index(p) in west|east for p in stops.values())
for key in ('m0','m1','m2','forest-ranger','forest-spirit','crypt-entrance'):assert index(stops[key]) in west,key
for i in range(len(walk)):
    if i in east or i in cut and walk[i]:walk[i]=2
def pack_cells(values):
    # Four cells per byte. 0 is blocked, 1 west, 2 east.
    packed=bytearray((len(values)+3)//4)
    for i,val in enumerate(values):packed[i//4]|=val<<(2*(i%4))
    return base64.b64encode(packed).decode()
depth=Image.open(folder/'Foreground.png').convert('L').filter(ImageFilter.MedianFilter(3))
layers=[];pieces=[];top=0
for low in range(1,256,12):
    high=low+11
    # A canopy projects above its roots. Ignore mixed antialias samples well
    # outside its possible vertical extent so the atlas stays compact.
    bottom=min(depth.height,round(min(high,255)*depth.height/255)+3)
    upper=max(0,round(low*depth.height/255)-round(depth.height*.34))
    window=depth.crop((0,upper,depth.width,bottom))
    alpha=window.point(lambda p:255 if low<=p<=high else 0)
    box=alpha.getbbox()
    if not box:continue
    piece=alpha.crop(box)
    layers.append([box[0],upper+box[1],piece.width,piece.height,top,min(255,low+5)/255])
    pieces.append(piece);top+=piece.height+1
atlas=Image.new('RGBA',(depth.width,top))
for layer,piece in zip(layers,pieces):
    atlas.paste((255,255,255,255),(0,layer[4],piece.width,layer[4]+piece.height),piece)
atlas.save(assets/'wildwood-valley-canopy.webp',method=6,lossless=True)
data=dict(width=w,height=h,stops={k:[round(x*100,3),round(y*100,3)] for k,(x,y) in stops.items()},
          gate=[round(v*100,3) for v in bridge],cells=pack_cells(walk),canopySize=list(depth.size),layers=layers)
(repo/'wildwood-valley-data.js').write_text('/* Generated by tools/blender/export_game.py */\nwindow.WildwoodValleyData='+json.dumps(data,separators=(',',':'))+';\n')
print(f'Exported {len(stops)} game stops, {len(layers)} depth bands, {len(west)} west and {len(east)} east cells')
